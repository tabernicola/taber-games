export const TABERDOKU_SIZES = [6, 7, 8, 9] as const;

/** Percentage of boards that must be solved to unlock the next level. */
export const TABERDOKU_LEVEL_UNLOCK_THRESHOLD = 40;

/** Number of boards (puzzles) contained in a single level. */
export const TABERDOKU_BOARDS_PER_LEVEL = 10;

/** Total number of boards (puzzles). */
export const TABERDOKU_TOTAL_BOARDS = TABERDOKU_PUZZLES.length;

/** Total number of levels (each containing TABERDOKU_BOARDS_PER_LEVEL boards). */
export const TABERDOKU_TOTAL_LEVELS = Math.ceil(
  TABERDOKU_TOTAL_BOARDS / TABERDOKU_BOARDS_PER_LEVEL,
);

export function taberdokuPuzzlesBySize(size: number): TaberdokuPuzzle[] {
  return TABERDOKU_PUZZLES.filter((p) => p.size === size);
}

export function findTaberdokuPuzzle(id: string): TaberdokuPuzzle | undefined {
  return TABERDOKU_PUZZLES.find((p) => p.id === id);
}

/** All puzzles in level order (board 1 = first, board 100 = last). */
export function starBattleAllPuzzlesSorted(): TaberdokuPuzzle[] {
  return [...TABERDOKU_PUZZLES];
}

/**
 * Converts a 1-indexed board number to its 1-indexed level number.
 * Board 1 → level 1, board 10 → level 1, board 11 → level 2, etc.
 */
export function boardToLevel(board: number): number {
  return Math.floor((board - 1) / TABERDOKU_BOARDS_PER_LEVEL) + 1;
}

/**
 * Returns the 1-indexed position of a board within its level (1–10).
 */
export function boardInLevel(board: number): number {
  return ((board - 1) % TABERDOKU_BOARDS_PER_LEVEL) + 1;
}

/**
 * Returns the 1-indexed board numbers that belong to a level.
 */
export function boardsInLevel(level: number): number[] {
  const start = (level - 1) * TABERDOKU_BOARDS_PER_LEVEL + 1;
  const end = Math.min(level * TABERDOKU_BOARDS_PER_LEVEL, TABERDOKU_TOTAL_BOARDS);
  const boards: number[] = [];
  for (let i = start; i <= end; i++) boards.push(i);
  return boards;
}

/**
 * Returns the progress percentage (0–100) of the level that the given
 * board belongs to, based on how many boards have already been completed.
 */
export function levelProgress(board: number): number {
  return Math.round(((boardInLevel(board) - 1) / TABERDOKU_BOARDS_PER_LEVEL) * 100);
}

/**
 * Returns the progress percentage (0–100) of a level based on the set of
 * completed board indices.
 */
export function levelProgressFromCompleted(completedBoards: Set<number>, level: number): number {
  const levelBoards = boardsInLevel(level);
  const completed = levelBoards.filter((b) => completedBoards.has(b)).length;
  return Math.round((completed / levelBoards.length) * 100);
}

/**
 * Whether a level is unlocked given the set of completed boards.
 * Level 1 is always unlocked; level N requires at least
 * TABERDOKU_LEVEL_UNLOCK_THRESHOLD % of level N-1's boards to be solved.
 */
export function isLevelUnlocked(level: number, completedBoards: Set<number>): boolean {
  if (level === 1) return true;
  const prevBoards = boardsInLevel(level - 1);
  const completedInPrev = prevBoards.filter((b) => completedBoards.has(b)).length;
  return (completedInPrev / prevBoards.length) * 100 >= TABERDOKU_LEVEL_UNLOCK_THRESHOLD;
}
